"""Data loaders that return a DataFrame with APP_FEATURES (where available) + `dropout` (0/1).

Two sources:

1. synthetic  - generated by ml/generate_synthetic.py; has all five app features.
                Use it for development and demos only.
2. uci        - Martins et al. (2021), "Predict students' dropout and academic
                success" (UCI ML Repository, id 697). Download data.csv from
                https://archive.ics.uci.edu/dataset/697 and pass its path.

The UCI dataset does not contain the same columns the app tracks, so we map:

    sgpa      <- 2nd-semester curricular-unit grade (0-20 scale) / 2
    cgpa      <- mean of non-zero 1st/2nd-semester grades / 2
    backlogs  <- (enrolled - approved) curricular units across both semesters
    fee_paid  <- "Tuition fees up to date"
    attendance_pct  -> NOT AVAILABLE (the dataset's "Daytime/evening attendance"
                       is class schedule, not an attendance percentage), so the
                       UCI-trained model is fit without it.
"""
from pathlib import Path

import numpy as np
import pandas as pd

from features import APP_FEATURES


def load_synthetic(path: Path) -> tuple[pd.DataFrame, list[str]]:
    df = pd.read_csv(path)
    missing = set(APP_FEATURES + ["dropout"]) - set(df.columns)
    if missing:
        raise ValueError(f"{path} is missing columns: {sorted(missing)}")
    return df[APP_FEATURES + ["dropout"]], list(APP_FEATURES)


def _col(df: pd.DataFrame, name: str) -> pd.Series:
    """Find a column tolerant of the stray whitespace/tabs present in the UCI headers."""
    lookup = {c.strip().lower(): c for c in df.columns}
    key = name.strip().lower()
    if key not in lookup:
        raise KeyError(f"Column '{name}' not found. Available: {list(lookup)[:10]}...")
    return df[lookup[key]]


def load_uci(path: Path, drop_enrolled: bool = False) -> tuple[pd.DataFrame, list[str]]:
    # The UCI file is ';'-separated (and one header contains a tab, which confuses delimiter sniffing).
    raw = pd.read_csv(path, sep=";")
    if raw.shape[1] == 1:  # someone re-saved it as comma-separated
        raw = pd.read_csv(path)
    target = _col(raw, "Target").astype(str).str.strip()
    if drop_enrolled:
        keep = target != "Enrolled"
        raw, target = raw[keep], target[keep]

    g1 = _col(raw, "Curricular units 1st sem (grade)").astype(float)
    g2 = _col(raw, "Curricular units 2nd sem (grade)").astype(float)
    grades = pd.concat([g1, g2], axis=1).replace(0, np.nan)

    enrolled = _col(raw, "Curricular units 1st sem (enrolled)") + _col(raw, "Curricular units 2nd sem (enrolled)")
    approved = _col(raw, "Curricular units 1st sem (approved)") + _col(raw, "Curricular units 2nd sem (approved)")

    df = pd.DataFrame(
        {
            "cgpa": (grades.mean(axis=1).fillna(0) / 2).round(2),
            "sgpa": (g2 / 2).round(2),
            "backlogs": (enrolled - approved).clip(lower=0).astype(int),
            "fee_paid": _col(raw, "Tuition fees up to date").astype(int),
            "dropout": (target == "Dropout").astype(int),
        }
    )
    features = [f for f in APP_FEATURES if f in df.columns]
    return df[features + ["dropout"]], features
